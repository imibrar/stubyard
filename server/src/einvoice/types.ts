export const ZATCA_CONFIG_DEFAULTS: ZatcaConfig = {
  env: 'developer-portal',
  otp: '',
  strictAuth: true,
  strictCsr: false,
  requireComplianceChecks: true,
  clearanceEnabled: true,
  checks: 'full',
  chainCheck: 'lint',
  reportingWindowHours: 24,
  caKeyPem: null,
  caCertPem: null,
};

const bool = (name: string, v: unknown): boolean => {
  if (typeof v !== 'boolean') throw new HttpError(400, `config.${name} must be true or false`);
  return v;
};
const oneOf = <T extends string>(name: string, v: unknown, allowed: readonly T[]): T => {
  if (!allowed.includes(v as T)) throw new HttpError(400, `config.${name} must be one of ${allowed.join(', ')}`);
  return v as T;
};
const pem = (name: string, v: unknown): string | null => {
  if (v === null || v === '') return null;
  if (typeof v !== 'string' || !v.includes('-----BEGIN ')) throw new HttpError(400, `config.${name} must be a PEM string`);
  return v;
};

/**
 * A full ZatcaConfig from a partial one: unset fields come from `prev` (an update) or the defaults; set fields are
 * validated (HttpError 400). Unknown keys are dropped.
 */
export function zatcaConfig(partial: Record<string, unknown> | null | undefined, prev: ZatcaConfig = ZATCA_CONFIG_DEFAULTS): ZatcaConfig {
  const p = partial ?? {};
  if (typeof p !== 'object' || Array.isArray(p)) throw new HttpError(400, 'config must be an object');
  const c: ZatcaConfig = { ...ZATCA_CONFIG_DEFAULTS, ...prev };
  if (p.env !== undefined) c.env = oneOf('env', p.env, ZATCA_ENVS);
  if (p.otp !== undefined) {
    const otp = p.otp === null ? '' : String(p.otp).trim();
    if (otp && !/^\d{6}$/.test(otp)) throw new HttpError(400, 'config.otp must be 6 digits, or empty to accept any 6 digits');
    c.otp = otp;
  }
  for (const k of ['strictAuth', 'strictCsr', 'requireComplianceChecks', 'clearanceEnabled'] as const) if (p[k] !== undefined) c[k] = bool(k, p[k]);
  if (p.checks !== undefined) c.checks = oneOf('checks', p.checks, ['basic', 'full'] as const);
  if (p.chainCheck !== undefined) c.chainCheck = oneOf('chainCheck', p.chainCheck, ['lint', 'error', 'off'] as const);
  if (p.reportingWindowHours !== undefined) {
    const h = Number(p.reportingWindowHours);
    if (!Number.isFinite(h) || h <= 0 || h > 24 * 365) throw new HttpError(400, 'config.reportingWindowHours must be a number of hours above 0 (at most 8760)');
    c.reportingWindowHours = h;
  }
  if (p.caKeyPem !== undefined) c.caKeyPem = pem('caKeyPem', p.caKeyPem);
  if (p.caCertPem !== undefined) c.caCertPem = pem('caCertPem', p.caCertPem);
  return c;
}

