import { smsSegments } from '../../messages/sms-segments.js';
import { BALANCE_FIELD, DLR_FIELD, SENDERS_FIELD, balanceOf, credentialOk, gccAlias, gccGate, intl, ksaPhone, list, pick, type GccError } from './gcc.js';
import { INBOUND_FIELD, cfg, fields, str, type ProviderAdapter, type Reply } from './types.js';

const SEND = /\/rest\/(?:SMS\/messages|Messages\/Send)\/?$/i;

/** Unifonic's error envelope: {success:false, message, errorCode, Status, data:{}} with a meaningful HTTP status. */
const err = (status: number, errorCode: string, message: string): Reply => ({
  status,
  body: { success: false, message, errorCode, Status: status === 401 || status === 402 ? 'Bad Request' : 'Failed', data: {} },
});

/** ER-1 / ER-2 / ER-04 are verified; the others follow the documented HTTP status table (errorCode values assumed). */
const NAMED: Record<GccError, Reply> = {
  auth: err(401, 'ER-1', 'Missing or Invalid AppSid'),
  sender: err(480, 'ER-480', 'This user cannot use the specified SenderID'),
  balance: err(400, 'ER-03', 'Insufficient balance'),
  number: err(482, 'ER-482', 'Invalid destination number'),
};

const created = (d = new Date()) => d.toISOString().replace('T', ' ').slice(0, 23);

/** Unifonic SMS REST API (el.cloud.unifonic.com): POST /rest/SMS/messages with AppSid in the body or query. */
export function unifonicAdapter(): ProviderAdapter {
  return {
    preset: 'unifonic',
    blockedAt: 'send',
    configFields: [
      { key: 'appSid', label: 'AppSid', hint: 'Optional. When set, any other AppSid gets 401 ER-1 "Missing or Invalid AppSid". Empty: any AppSid works.', secret: true },
      DLR_FIELD,
      BALANCE_FIELD,
      SENDERS_FIELD,
      INBOUND_FIELD,
    ],

    match(req) {
      if ((req.method === 'POST' || req.method === 'GET') && SEND.test(req.path)) return { kind: 'send' };
      return null;
    },

    parse(req, ctx) {
      const f = fields(req);
      const appSid = str(pick(f, 'AppSid'));
      if (!appSid) return { error: err(402, 'ER-2', 'No AppSid Parameter Specified') };
      if (!credentialOk(ctx, 'appSid', appSid)) return { error: NAMED.auth };
      const rawTo = list(pick(f, 'Recipient'))[0] ?? null;
      if (!rawTo) return { error: err(422, 'ER-22', 'No recipient parameter specified') };
      const to = ksaPhone(rawTo);
      if (!to || to.length < 9) return { error: err(400, 'ER-04', 'Dest num is too short') };
      const body = str(pick(f, 'Body'));
      if (!body) return { error: err(421, 'ER-21', 'No message body specified') };
      const sender = str(pick(f, 'SenderID'));
      const gate = gccGate(ctx, sender);
      if (gate) return { error: NAMED[gate] };
      const cb = str(pick(f, 'statusCallback'));
      return {
        channel: 'sms',
        to,
        from: sender,
        body,
        statusCallbackUrl: cb && /^https?:\/\//i.test(cb) ? cb : null,
        extra: { correlationId: str(pick(f, 'CorrelationID')), metadata: { correlationId: str(pick(f, 'CorrelationID')) } },
      };
    },

    // Unifonic MessageIDs are 14-digit integers.
    newMessageId: () => String(42_000_000_000_000 + Math.floor(Math.random() * 999_999_999_999)),

    accepted(ctx, m) {
      const units = smsSegments(m.parsed.body).segments;
      return {
        status: 200,
        body: {
          success: true,
          message: '',
          errorCode: 'ER-00',
          data: {
            MessageID: Number(m.id),
            CorrelationID: m.parsed.extra?.correlationId ?? '',
            Status: 'Sent',
            NumberOfUnits: units,
            Cost: Number((units * 0.05).toFixed(4)),
            Balance: balanceOf(ctx),
            Recipient: intl(m.parsed.to),
            TimeCreated: created(new Date(m.createdAt)),
            CurrencyCode: 'SAR',
          },
        },
      };
    },

    sendError(_ctx, kind, _parsed, code, message) {
      const named = gccAlias(code);
      if (named) return message ? err(NAMED[named].status, (NAMED[named].body as { errorCode: string }).errorCode, message) : NAMED[named];
      switch (kind) {
        case 'down':
          return err(503, code ?? 'ER-503', message ?? 'Service Unavailable');
        case 'rate_limit':
          return err(429, code ?? 'ER-429', message ?? 'Too many requests generated by this user');
        case 'blocked':
        case 'opt_out':
          return err(400, code ?? 'ER-400', message ?? 'Recipient is blocked');
        default:
          return err(482, code ?? 'ER-482', message ?? 'Invalid destination number');
      }
    },

    defaultFailure: (kind) => (kind === 'blocked' ? { code: 'REJECTD', message: 'Rejected by the operator' } : { code: 'UNDELIV', message: 'Undeliverable' }),

    notFound: (req) => err(404, 'ER-404', `${req.method} ${req.path} is not a Unifonic SMS endpoint (use POST /rest/SMS/messages)`),

    // Unifonic's DLR webhook (eventName "dlr") carries only the final status.
    statusCallback(ctx, m, status, e, url) {
      if (status !== 'delivered' && status !== 'failed') return null;
      const units = smsSegments(m.bodyText ?? '').segments;
      const now = created();
      return {
        url,
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          eventName: 'dlr',
          productName: 'sms',
          accountId: cfg(ctx, 'appSid') ?? 'stubyard',
          timeStamp: new Date().toISOString(),
          body: {
            submitUnitCount: units,
            deliveredUnitCount: status === 'delivered' ? units : 0,
            submitDate: created(new Date(m.createdAt)),
            doneDate: now,
            finalStatus: status === 'delivered' ? 'DELIVRD' : e?.code === 'REJECTD' ? 'REJECTD' : 'UNDELIV',
            errorCode: status === 'failed' ? e?.code ?? '' : '',
            freeText: status === 'failed' ? e?.message ?? '' : '',
            destinationAddress: intl(m.to),
            correlationId: String(m.metadata.correlationId ?? ''),
            messageId: Number(m.providerMessageId),
          },
        }),
      };
    },

    inbound(_ctx, m, url) {
      return {
        url,
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ messageId: m.id, from: intl(m.from), to: intl(m.to), body: m.text, timeStamp: new Date().toISOString() }),
      };
    },
  };
}
