import type { Message } from '../api';
import { Badge, fmtBytes } from './ui';

/** Structured WhatsApp content stubyard stores on messages (`metadata.wa`), see server/src/providers/adapters/wa-content.ts. */
export interface WaButton {
  id: string;
  title: string;
  kind: 'reply' | 'quick_reply' | 'url';
  url?: string;
}
export interface WaContent {
  type: string;
  text?: string | null;
  caption?: string | null;
  media?: { link: string | null; id: string | null; filename: string | null; mimeType?: string | null; fileSize?: number | null };
  mediaUrls?: string[];
  location?: { latitude: number; longitude: number; name: string | null; address: string | null };
  contacts?: { name: string; phones: string[]; emails: string[] }[];
  interactive?: { type: string; header: string | null; body: string; footer: string | null; buttons?: WaButton[]; listButton?: string; sections?: { title: string | null; rows: { id: string; title: string; description?: string | null }[] }[] };
  reaction?: { messageId: string; emoji: string };
  template?: { name: string; language: string | null; buttons: WaButton[] };
  reply?: { kind: string; id: string; title: string; description?: string | null };
  replyTo?: string | null;
}

export interface ReplyOption {
  kind: 'button_reply' | 'list_reply' | 'button';
  id: string;
  title: string;
  description?: string | null;
}

export const waOf = (m: Message): WaContent | null => (m.metadata?.wa && typeof m.metadata.wa === 'object' ? (m.metadata.wa as WaContent) : null);

/** Buttons / list rows / template quick replies the user can tap (same rules as the server). */
export function replyOptions(m: Message): ReplyOption[] {
  const wa = waOf(m);
  if (!wa || m.direction !== 'outbound') return [];
  if (wa.interactive?.buttons) return wa.interactive.buttons.filter((b) => b.kind === 'reply').map((b) => ({ kind: 'button_reply', id: b.id, title: b.title }));
  if (wa.interactive?.sections) return wa.interactive.sections.flatMap((s) => s.rows.map((r) => ({ kind: 'list_reply' as const, id: r.id, title: r.title, description: r.description })));
  if (wa.template?.buttons) return wa.template.buttons.filter((b) => b.kind === 'quick_reply').map((b) => ({ kind: 'button', id: b.id, title: b.title }));
  return [];
}

/** Short type label for the timeline (null for plain text). */
export function messageKind(m: Message): string | null {
  if (m.metadata?.voice) return 'voice call';
  const wa = waOf(m);
  if (wa?.reply) return wa.reply.kind === 'list_reply' ? 'list reply' : 'button reply';
  if (wa && wa.type !== 'text') return wa.type === 'interactive' ? (wa.interactive?.type === 'list' ? 'list' : wa.interactive?.type === 'cta_url' ? 'link button' : 'buttons') : wa.type;
  return null;
}

/** "Verify" badge text for codes generated by Twilio Verify / Vonage Verify v2. */
export function verifyLabel(m: Message): string | null {
  const v = m.metadata?.verify as { api?: string } | undefined;
  return v?.api ? (v.api === 'twilio-verify' ? 'Twilio Verify' : 'Vonage Verify') : null;
}

/** Rich WhatsApp content in the message viewer: media, buttons, lists, location, contacts, reactions. */
export function WaContentView({ m, slug, instanceSlug }: { m: Message; slug: string; instanceSlug?: string }) {
  const wa = waOf(m);
  if (!wa || wa.type === 'text') return null;
  const mediaHref = (id: string) => (instanceSlug ? `/mock/${slug}/${instanceSlug}/whatsapp_business/attachments/?mid=${encodeURIComponent(id)}` : null);
  return (
    <div className="wa-content stack">
      <div className="row" style={{ gap: 6 }}>
        <Badge kind="accent">{messageKind(m) ?? wa.type}</Badge>
        {wa.template && (
          <span className="small muted">
            template <span className="mono">{wa.template.name}</span>
            {wa.template.language ? ` · ${wa.template.language}` : ''}
          </span>
        )}
      </div>
      {wa.media && (
        <div className="list-row">
          <div className="grow" style={{ minWidth: 0 }}>
            <div className="ellipsis">
              {wa.media.link ? (
                <a href={wa.media.link} target="_blank" rel="noreferrer">
                  {wa.media.filename ?? wa.media.link}
                </a>
              ) : mediaHref(wa.media.id!) ? (
                <a href={mediaHref(wa.media.id!)!} target="_blank" rel="noreferrer">
                  {wa.media.filename ?? `media ${wa.media.id}`}
                </a>
              ) : (
                <span className="mono">{wa.media.id}</span>
              )}
            </div>
            <div className="row-meta small faint">
              {wa.media.id ? `uploaded media ${wa.media.id}` : 'by link'}
              {wa.media.mimeType ? ` · ${wa.media.mimeType}` : ''}
              {wa.media.fileSize ? ` · ${fmtBytes(wa.media.fileSize)}` : ''}
            </div>
          </div>
        </div>
      )}
      {wa.mediaUrls?.map((u) => (
        <a key={u} href={u} target="_blank" rel="noreferrer" className="ellipsis">
          {u}
        </a>
      ))}
      {wa.caption && <div>{wa.caption}</div>}
      {wa.location && (
        <div>
          📍 {[wa.location.name, wa.location.address].filter(Boolean).join(', ') || 'Location'}{' '}
          <a href={`https://www.openstreetmap.org/?mlat=${wa.location.latitude}&mlon=${wa.location.longitude}#map=16/${wa.location.latitude}/${wa.location.longitude}`} target="_blank" rel="noreferrer" className="small">
            {wa.location.latitude}, {wa.location.longitude} ↗
          </a>
        </div>
      )}
      {wa.contacts?.map((c, i) => (
        <div key={i} className="list-row">
          <div className="grow">
            <strong>{c.name}</strong>
            <div className="row-meta small muted">{[...c.phones, ...c.emails].join(' · ') || 'no phone / email'}</div>
          </div>
        </div>
      ))}
      {wa.reaction && (
        <div>
          {wa.reaction.emoji || '(reaction removed)'} <span className="small faint">on {wa.reaction.messageId}</span>
        </div>
      )}
      {wa.interactive && (
        <div className="stack" style={{ gap: 6 }}>
          {wa.interactive.header && <strong>{wa.interactive.header}</strong>}
          <div>{wa.interactive.body}</div>
          {wa.interactive.footer && <div className="small faint">{wa.interactive.footer}</div>}
          {wa.interactive.buttons && (
            <div className="row" style={{ gap: 6 }}>
              {wa.interactive.buttons.map((b) =>
                b.url ? (
                  <a key={b.id} className="btn sm" href={b.url} target="_blank" rel="noreferrer">
                    {b.title} ↗
                  </a>
                ) : (
                  <span key={b.id} className="btn sm wa-btn" title={`id: ${b.id}`}>
                    {b.title}
                  </span>
                ),
              )}
            </div>
          )}
          {wa.interactive.sections && (
            <div className="stack" style={{ gap: 4 }}>
              <span className="small muted">List button: “{wa.interactive.listButton}”</span>
              {wa.interactive.sections.map((s, i) => (
                <div key={i} className="stack" style={{ gap: 2 }}>
                  {s.title && <span className="small faint">{s.title}</span>}
                  {s.rows.map((r) => (
                    <div key={r.id} className="list-row" title={`id: ${r.id}`}>
                      <div className="grow">
                        {r.title}
                        {r.description && <div className="row-meta small faint">{r.description}</div>}
                      </div>
                      <span className="mono small faint">{r.id}</span>
                    </div>
                  ))}
                </div>
              ))}
            </div>
          )}
        </div>
      )}
      {wa.template?.buttons && wa.template.buttons.length > 0 && (
        <div className="row" style={{ gap: 6 }}>
          {wa.template.buttons.map((b) => (
            <span key={b.id} className="btn sm wa-btn" title={`payload: ${b.id}`}>
              {b.title}
            </span>
          ))}
        </div>
      )}
      {wa.reply && (
        <div className="small">
          Tapped <strong>{wa.reply.title}</strong> <span className="mono faint">({wa.reply.id})</span>
        </div>
      )}
    </div>
  );
}
